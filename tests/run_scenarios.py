"""Run every scenario in tests/scenarios.json through explain_prediction() and write a readable report.

  python tests/run_scenarios.py                 # -> tests/results/scenario_report.md + scenario_results.csv
  python tests/run_scenarios.py --update-golden # re-baseline tests/golden/scenarios_golden.json (after an intentional retrain)
"""
import argparse
import json
from pathlib import Path

import pandas as pd

from roadmind.explain import explain_prediction

HERE = Path(__file__).parent
SCEN, GOLD, OUT = HERE / "scenarios.json", HERE / "golden" / "scenarios_golden.json", HERE / "results"


def run() -> list[dict]:
    rows = []
    for s in json.loads(SCEN.read_text()):
        r = explain_prediction(s["input"], top_k=4)
        rows.append({"id": s["id"], "why": s["why"], "input": s["input"], "risk_level": r["risk_level"],
                     "probability": r["probability"],
                     "factors": [(f["description"], f["shap_log_odds"]) for f in r["top_factors"]],
                     "message": r["suggested_message"]})
    return rows


def write_report(rows: list[dict]) -> None:
    OUT.mkdir(exist_ok=True)
    pd.DataFrame([{"id": r["id"], "risk_level": r["risk_level"], "score": r["probability"],
                   "top_factors": " | ".join(f"{d} ({v:+.2f})" for d, v in r["factors"]), "why": r["why"]}
                  for r in rows]).to_csv(OUT / "scenario_results.csv", index=False)
    L = ["# Scenario report", "", "Generated by `python tests/run_scenarios.py`. Score = model probability of a high-impact "
         "outcome given an accident (uncalibrated out of distribution); the tier is what a driver would see.", "",
         "| Scenario | What it tests | Tier | Score | Top factors (SHAP log-odds) |", "|---|---|---|---|---|"]
    for r in rows:
        fac = "; ".join(f"{d} ({v:+.2f})" for d, v in r["factors"])
        L.append(f"| {r['id']} | {r['why']} | **{r['risk_level']}** | {r['probability']:.3f} | {fac} |")
    L += ["", "## Driver messages", ""]
    for r in rows:
        L += [f"### {r['id']}", "```", r["message"], "```", ""]
    (OUT / "scenario_report.md").write_text("\n".join(L))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--update-golden", action="store_true")
    a = ap.parse_args()
    rows = run()
    write_report(rows)
    if a.update_golden:
        GOLD.parent.mkdir(exist_ok=True)
        GOLD.write_text(json.dumps({r["id"]: {"risk_level": r["risk_level"], "probability": r["probability"]}
                                    for r in rows}, indent=2))
        print(f"golden snapshot updated: {GOLD}")
    print((OUT / "scenario_report.md").read_text().split("## Driver messages")[0])
